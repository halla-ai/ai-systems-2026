"""Generate benchmark_project api.py + README.md from benchmark_cases.json."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CASES_PATH = ROOT / "tests" / "fixtures" / "benchmark_cases.json"
OUT_DIR = ROOT / "tests" / "fixtures" / "benchmark_project"


def _readme_sig(case: dict) -> str:
    params = case.get("doc_params", [])
    param_str = ", ".join(
        f"{p['name']}: {p['type']}" + (f" = {p['default']}" if "default" in p else "")
        for p in params
    )
    ret = case.get("doc_return", "None")
    return f"`{case['function']}({param_str}) -> {ret}`"


def _code_params(case: dict) -> str:
    parts = []
    for p in case.get("code_params", case.get("doc_params", [])):
        ann = p.get("type", "")
        default = p.get("default")
        if default is not None:
            parts.append(f"{p['name']}: {ann} = {default!r}" if isinstance(default, str) else f"{p['name']}: {ann} = {default}")
        else:
            parts.append(f"{p['name']}: {ann}")
    return ", ".join(parts)


def _code_body(case: dict) -> str:
    return case.get("code_body", "    return None")


def generate() -> None:
    data = json.loads(CASES_PATH.read_text(encoding="utf-8"))
    cases = data["cases"]
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "tests").mkdir(exist_ok=True)

    api_lines = ['"""Benchmark API — generated by scripts/generate_benchmark_fixture.py."""\n']
    readme_lines = ["# Benchmark API\n", "\n## Functions\n"]

    for case in cases:
        fn = case["function"]
        params = _code_params(case)
        ret_ann = case.get("code_return_ann", case.get("doc_return", "None"))
        api_lines.append(f"\ndef {fn}({params}) -> {ret_ann}:")
        api_lines.append(f'    """{case.get("docstring", fn)}."""')
        api_lines.append(_code_body(case))
        api_lines.append("")
        readme_lines.append(f"\n{_readme_sig(case)}\n")
        readme_lines.append(f"\n{case.get('doc_blurb', fn)}\n")

    (OUT_DIR / "api.py").write_text("\n".join(api_lines), encoding="utf-8")
    (OUT_DIR / "README.md").write_text("".join(readme_lines), encoding="utf-8")

    test_lines = [
        '"""Minimal tests so benchmark project pytest succeeds after doc-only patch."""',
        "from benchmark_project.api import *  # noqa: F403",
        "",
        "def test_imports():",
        "    assert callable(parse_json) if 'parse_json' in dir() else True",
    ]
    # Use relative import path
    test_content = '''"""Minimal tests for benchmark fixture."""
import importlib.util
from pathlib import Path

def test_module_imports():
    api_path = Path(__file__).resolve().parent.parent / "api.py"
    spec = importlib.util.spec_from_file_location("benchmark_api", api_path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    assert hasattr(mod, "clean_01")
'''
    (OUT_DIR / "tests" / "test_benchmark.py").write_text(test_content, encoding="utf-8")

    pyproject = """[project]
name = "benchmark-project"
version = "0.0.0"
requires-python = ">=3.10"

[tool.pytest.ini_options]
testpaths = ["tests"]
"""
    (OUT_DIR / "pyproject.toml").write_text(pyproject, encoding="utf-8")

    ground_truth = {
        "project": "benchmark_project",
        "version": 1,
        "tier": "synthetic_curated",
        "caveat": (
            "Synthetic set generated to match detector rules; expect optimistic scores. "
            "See realistic_fixtures.sample_project in benchmark_report.json for honest metrics."
        ),
        "description": data.get("description", ""),
        "targets": data.get("targets", {}),
        "clean_functions": [c["function"] for c in cases if c.get("clean")],
        "expected_drifts": [
            {
                "module": "api",
                "function": c["function"],
                "drift_type": c["expected_drift_type"],
                "category": c["category"],
            }
            for c in cases
            if c.get("expected_drift_type")
        ],
    }
    gt_path = ROOT / "tests" / "fixtures" / "benchmark_ground_truth.json"
    gt_path.write_text(json.dumps(ground_truth, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"Wrote {OUT_DIR / 'api.py'} ({len(cases)} functions)")
    print(f"Wrote {gt_path} ({len(ground_truth['expected_drifts'])} expected drifts)")


if __name__ == "__main__":
    generate()
